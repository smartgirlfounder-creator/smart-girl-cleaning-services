// Plays through the real workflow with sample data, saving element screenshots and facts for review.
import { chromium } from "playwright-core";
import { spawn } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
const root = process.argv[2];
mkdirSync("explore/probe", { recursive: true });
const server = spawn("python3", ["-m", "http.server", "4200", "--bind", "127.0.0.1"], { cwd: root, stdio: "pipe" });
process.on("exit", () => server.kill());
await new Promise((r) => setTimeout(r, 1200));
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
page.setDefaultTimeout(5000);
const logs = [];
const step = (m) => console.log("step:", m);
page.on("pageerror", (e) => logs.push(`pageerror: ${e}`));
page.on("dialog", (d) => { logs.push(`dialog: ${d.type()} ${d.message()}`); d.accept(); });
page.on("popup", (p) => { logs.push(`popup: ${p.url()}`); p.close(); });
await page.goto("http://127.0.0.1:4200/index.html");
await page.fill("#gateName", "Demo User");
await page.fill("#gateCode", "SG-48291");
await page.click("text=Unlock Calculator");
await page.waitForTimeout(600);
const tab = (t) => page.evaluate((x) => document.querySelector(`.tab-btn[onclick*="'${x}'"]`).click(), t);
const facts = {};
facts.currencies = await page.$$eval("#currency option, select[id*=urr] option", (o) => o.map((x) => x.value + ":" + x.textContent));
facts.setupIds = await page.$$eval("#setup input, #setup select, #setup textarea, [id='setup'] input", (o) => o.map((x) => x.id)).catch(() => []);
step('// Setup');
// Setup
await page.fill("#bizName", "Sparkle Pros Cleaning");
await page.fill("#ownerName", "Ada Okafor");
await page.fill("#bizPhone", "0801 234 5678");
await page.fill("#bizEmail", "hello@sparklepros.example").catch(() => logs.push("no bizEmail"));
await page.fill("#bankName", "Demo Bank");
await page.fill("#accName", "Sparkle Pros Cleaning");
await page.fill("#accNum", "0123456789");
await page.fill("input[placeholder='e.g. Kafayat Olaitan']", "Ada Okafor");
await page.dispatchEvent("#bizName", "change");
await page.screenshot({ path: "explore/probe/setup.png", fullPage: true });
step('// Calculator');
// Calculator
await tab("calculator");
await page.fill("#cName", "Mrs. Bola Adeyemi");
await page.fill("#cPhone", "0802 345 6789");
await page.fill("#cAddr", "14 Palm Grove Close, Lekki");
await page.selectOption("#type", "deep");
await page.click("button[onclick='adjustBed(1)']");
await page.click("button[onclick='adjustStaff(1)']");
await page.fill("#difficultyMult", "1.2");
await page.dispatchEvent("#difficultyMult", "change");
await page.waitForTimeout(300);
facts.view1 = await page.$eval(".breakdown", (e) => e.innerText);
facts.total1 = await page.$eval("#totalCost", (e) => e.textContent);
step('await page.click("text=➕ Add this service to the quote");');
await page.click("text=➕ Add this service to the quote");
await page.waitForTimeout(300);
await page.selectOption("#type", "uphol");
await page.fill("#trans", "0"); await page.dispatchEvent("#trans", "change");
await page.waitForTimeout(300);
await page.click("text=➕ Add this service to the quote");
await page.waitForTimeout(500);
facts.total2 = await page.$eval("#totalCost", (e) => e.textContent);
await page.screenshot({ path: "explore/probe/calc.png", fullPage: true });
step('await page.click("text=💾 Save This Quote to History");');
await page.click("text=💾 Save This Quote to History");
await page.waitForTimeout(500);
step('// Invoice');
// Invoice
await tab("invoice");
await page.click("text=↻ Load from Calculator");
await page.waitForTimeout(400);
facts.invoiceIds = await page.$$eval("#invoice input, #invoice select", (o) => o.map((x) => x.id + "=" + x.value)).catch(() => []);
await page.screenshot({ path: "explore/probe/invoice-before.png", fullPage: true });
step("invoice fill");
const pm = await page.$$eval("#invPayMethod option, #invoice select option", (o) => o.map((x) => x.value + ":" + x.textContent));
facts.payMethods = pm;
const sel = await page.$$eval("#invoice select", (o) => o.map((x) => x.id));
facts.invoiceSelects = sel;
await page.fill("#invAmountReceived, #amountReceived, #invReceived", "148200").catch(async () => {
  const ids = await page.$$eval("#invoice input", (o) => o.map((x) => x.id));
  logs.push("invoice inputs: " + ids.join(","));
});
for (const id of sel) await page.selectOption("#" + id, { index: 1 }).catch(() => logs.push("sel fail " + id));
await page.click("text=✓ Generate Invoice");
await page.waitForTimeout(600);
await page.screenshot({ path: "explore/probe/invoice.png", fullPage: true });
step("delivery");
await tab("delivery");
await page.click("text=⬆ Load from Calculator");
await page.waitForTimeout(300);
await page.click("text=✓ Generate Delivery Report");
await page.waitForTimeout(600);
await page.screenshot({ path: "explore/probe/delivery.png", fullPage: true });
step("history");
await tab("history");
await page.waitForTimeout(400);
await page.screenshot({ path: "explore/probe/history.png", fullPage: true });
facts.historyText = (await page.$eval("body", (b) => b.innerText)).slice(0, 1500);
step("dashboard");
await tab("dashboard");
await page.waitForTimeout(400);
await page.screenshot({ path: "explore/probe/dashboard.png", fullPage: true });
step("proposal");
await tab("proposal");
await page.click("text=+ New proposal");
await page.waitForTimeout(600);
await page.screenshot({ path: "explore/probe/proposal.png", fullPage: true });
writeFileSync("explore/probe/facts.json", JSON.stringify(facts, null, 1));
console.log(JSON.stringify({payMethods: facts.payMethods, invoiceSelects: facts.invoiceSelects, historyText: facts.historyText}, null, 1).slice(0, 4000));
console.log(logs.join("\n"));
await browser.close();
process.exit(0);
