import { chromium } from "playwright-core";
import { spawn } from "node:child_process";
import { join } from "node:path";
const cwd = process.argv[2];
const server = spawn(join(cwd, "node_modules", ".bin", "vite"), ["preview", "--port", "4190", "--strictPort"], { cwd, stdio: "pipe" });
await new Promise((r) => server.stdout.on("data", (d) => String(d).includes("4190") && r()));
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await ctx.newPage();
const errors = [];
page.on("console", (m) => m.type() === "error" && !/supabase|net::ERR/i.test(m.text()) && errors.push(m.text()));
await page.goto("http://localhost:4190/");
await page.waitForSelector(".home");
await page.waitForFunction(() => navigator.serviceWorker?.controller || navigator.serviceWorker?.ready.then(() => true), null, { timeout: 15000 });
await page.waitForTimeout(1500);
const cdp = await ctx.newCDPSession(page);
const inst = await cdp.send("Page.getInstallabilityErrors");
const man = await cdp.send("Page.getAppManifest");
console.log("installability errors:", JSON.stringify(inst.installabilityErrors));
console.log("manifest errors:", JSON.stringify(man.errors));
console.log("sw ready:", await page.evaluate(async () => !!(await navigator.serviceWorker.ready).active));
console.log("install card shown:", await page.isVisible(".install-card"));
await page.click('[data-action="install"]');
console.log("help modal shown:", await page.isVisible("#install-title"));
await page.screenshot({ path: process.argv[3] });
// Offline: reload with network off
await ctx.setOffline(true);
await page.reload();
console.log("works offline:", await page.isVisible(".home"));
console.log("console errors:", JSON.stringify(errors));
await browser.close();
server.kill();
